"""Generate reviewed schema and a private restore payload from an external backup.
Usage: python scripts/prepare-neon-recovery.py /path/to/recovery /private/output.json
Never place the restore payload in the repository.
"""
import json, sys, pathlib, collections
root=pathlib.Path(sys.argv[1]); m=json.loads((root/'schema-metadata.json').read_text()); b=json.loads((root/'agenda-backup.json').read_text())
q=lambda s:'"'+s.replace('"','""')+'"'
tables=collections.defaultdict(list)
for c in m['columns']: tables[(c['table_schema'],c['table_name'])].append(c)
sql=['CREATE SCHEMA IF NOT EXISTS private', 'REVOKE ALL ON SCHEMA private FROM PUBLIC', '''CREATE TABLE private.admin_users (user_id text PRIMARY KEY, created_at timestamptz NOT NULL DEFAULT now())''', '''CREATE FUNCTION private.is_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$ SELECT EXISTS(SELECT 1 FROM private.admin_users WHERE user_id = nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub') $$''']
for (schema,table),cols in sorted(tables.items()):
 parts=[]
 for c in sorted(cols,key=lambda c:c['ordinal_position']):
  s=q(c['column_name'])+' '+c['data_type']
  if c['is_identity']=='YES':s+=' GENERATED BY DEFAULT AS IDENTITY'
  elif c['is_generated']=='ALWAYS':s+=' GENERATED ALWAYS AS ('+c['generation_expression']+') STORED'
  elif c['column_default']:s+=' DEFAULT '+c['column_default']
  if c['is_nullable']=='NO':s+=' NOT NULL'
  parts.append(s)
 sql.append('CREATE TABLE '+q(schema)+'.'+q(table)+' (\n'+',\n'.join(parts)+'\n)')
for c in sorted(m['constraints'], key=lambda c:c['definition'].startswith('FOREIGN')):
 sql.append('ALTER TABLE '+q(c['schema'])+'.'+q(c['table'])+' ADD CONSTRAINT '+q(c['name'])+' '+c['definition'])
# No roles or Supabase auth schema required: identity is supplied only by our backend.
functions=[]
for f in m['functions']:
 s=f['definition'].replace("auth.uid() = '62eeb246-e764-44d5-b976-e596d8cb6be9'::uuid",'private.is_admin()').replace("auth.uid() is distinct from '62eeb246-e764-44d5-b976-e596d8cb6be9'::uuid",'NOT private.is_admin()').replace('auth.uid() is null',"nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub' is null")
 s=s.replace("current_setting('request.jwt.claims', true)::jsonb", "nullif(current_setting('request.jwt.claims', true),'')::jsonb")
 functions.append(s)
# Files in git contain schema only. Restored customer data stays outside git.
pathlib.Path('migrations/neon/001-schema.sql').write_text(';\n\n'.join(sql)+';\n')
post=functions+[t['definition'] for t in m['triggers']]+['REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC','REVOKE ALL ON ALL TABLES IN SCHEMA private FROM PUBLIC','REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA private FROM PUBLIC']
post += ['ALTER TABLE public.'+q(t)+' ENABLE ROW LEVEL SECURITY' for s,t in tables if s=='public']
post += ['CREATE INDEX bookings_date_time_idx ON public.bookings(date,time)','CREATE INDEX bookings_phone_idx ON public.bookings(client_phone_key)','CREATE INDEX booking_limits_ip_time_idx ON private.nails_booking_limits(ip,recorded_at)','CREATE INDEX booking_limits_phone_time_idx ON private.nails_booking_limits(phone,recorded_at)']
pathlib.Path('migrations/neon/002-guards.sql').write_text(';\n\n'.join(post)+';\n')
inserts=[]
for table in ['services','ai_color_catalog','bookings','booking_slots','schedule_blocks','booking_payments']:
 rows=b.get(table,[])
 if not rows:continue
 cols=[c['column_name'] for c in sorted(tables[('public',table)],key=lambda c:c['ordinal_position']) if c['is_generated']!='ALWAYS' and c['column_name'] in rows[0]]
 # json_populate_record preserves exact types and timestamps; no executable interpolation from data.
 value=json.dumps(rows,ensure_ascii=False).replace("'","''")
 inserts.append('INSERT INTO public.'+q(table)+' ('+','.join(map(q,cols))+') SELECT '+','.join(map(q,cols))+" FROM json_populate_recordset(null::public."+q(table)+",'"+value+"'::json)")
pathlib.Path(sys.argv[2]).write_text(json.dumps(sql+inserts+post))
print('Prepared schema and private restore:', {t:len(b.get(t,[])) for t in ['services','bookings','booking_slots','schedule_blocks','booking_payments']})
